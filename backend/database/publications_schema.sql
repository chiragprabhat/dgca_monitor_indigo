    publication_id   TEXT PRIMARY KEY,
    title             TEXT NOT NULL,
    category          TEXT NOT NULL,
    published_date    TEXT,
    publication_url   TEXT,
    pdf_url           TEXT,
    content_hash      TEXT NOT NULL,
    document_hash     TEXT,
