-- Keep the SQLite timestamp strings, including UTC defaults and ISO values written by the app.
CREATE OR REPLACE FUNCTION dgca_utc_now() RETURNS TEXT LANGUAGE sql STABLE
  RETURN to_char(statement_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS');

CREATE TABLE IF NOT EXISTS updates (
  id TEXT PRIMARY KEY,
  section TEXT NOT NULL,
  title TEXT NOT NULL,
  description TEXT,
  publication_date TEXT,
  pdf_urls TEXT,
  source_page_url TEXT,
  detected_at TEXT DEFAULT dgca_utc_now(),
  updated_at TEXT DEFAULT dgca_utc_now(),
  is_notified BIGINT DEFAULT 0,
  notified_at TEXT,
  hash TEXT UNIQUE
);

CREATE TABLE IF NOT EXISTS notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  update_id TEXT,
  recipient_email TEXT,
  sent_at TEXT DEFAULT dgca_utc_now(),
  status TEXT,
  error_message TEXT,
  FOREIGN KEY (update_id) REFERENCES updates(id)
);

