CREATE EXTENSION IF NOT EXISTS unaccent WITH SCHEMA public;
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_ts_dict WHERE dictname = 'dgca_english_stem' AND dictnamespace = 'public'::regnamespace
  ) THEN
    CREATE TEXT SEARCH DICTIONARY public.dgca_english_stem (TEMPLATE = pg_catalog.snowball, LANGUAGE = english);
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_ts_config WHERE cfgname = 'dgca_search' AND cfgnamespace = 'public'::regnamespace
  ) THEN
    CREATE TEXT SEARCH CONFIGURATION public.dgca_search (COPY = pg_catalog.simple);
    ALTER TEXT SEARCH CONFIGURATION public.dgca_search
      ALTER MAPPING FOR asciiword, word, hword, hword_asciipart, asciihword, hword_part
      WITH public.unaccent, public.dgca_english_stem;
  END IF;
END $$;

CREATE OR REPLACE FUNCTION dgca_search_vector(title TEXT, body TEXT) RETURNS tsvector
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
  RETURN setweight(to_tsvector('public.dgca_search', coalesce(title, '')), 'A') ||
         setweight(to_tsvector('public.dgca_search', coalesce(body, '')), 'D');

CREATE INDEX IF NOT EXISTS updates_fts ON updates USING GIN (dgca_search_vector(title, pdf_text));
